#pragma once
#include <cstdint>

// Canonical parameter identity. Continuous params are stored normalised
// (0..1) in PatchState and mapped to engineering units inside the DSP.
// The `cc` values mirror the ECHON 6 manual's CC implementation chart so a
// later MIDI/SysEx layer is a direct map. cc == -1 => not MIDI-mapped here.

namespace tides::params
{
    enum class P : uint16_t
    {
        // ---- Exciter VCO / Noise ----
        ExWave,            // morph: sine..tri..ramp..pulse..square (/ext-in)
        ExCoarseFreq,
        ExFineFreq,
        ExNoiseSHRate,
        ExWaveNoiseMix,
        ExLevel,

        // ---- Exciter DADSR ----
        EnvOnsetDelay,
        EnvAttack,
        EnvDecay,
        EnvSustain,
        EnvRelease,

        // ---- BBD Resonator ----
        ResInputFilter,
        ResFeedbackFilter,
        ResFeedback,
        ResFineTune,
        ResGlide,

        // ---- Output ----
        OutDryWet,
        OutPanning,
        OutLevel,
        WildTame,   // global character macro: clean+precise <-> noisy+alive
        Master,

        NumParams
    };

    constexpr int kNumParams = static_cast<int>(P::NumParams);

    struct Descriptor
    {
        const char* id;     // stable string id (state + automation)
        const char* name;   // display name
        float       def;    // default (normalised) = INIT patch value
        int         cc;     // ECHON 6 CC number, or -1
    };

    // INIT sound (manual p.34): "a sustained sinusoidal tone generated by the
    // Exciter, with keyboard tracking across the full range" and the
    // resonator effectively bypassed (Dry/Wet fully CCW).
    inline const Descriptor& descriptor(P p)
    {
        static const Descriptor table[kNumParams] = {
            { "ex_wave",        "Wave",            0.0f, 15 },
            { "ex_coarse",      "Coarse Freq",     0.5f, 17 },
            { "ex_fine",        "Fine Freq",       0.5f, 18 },
            { "ex_sh_rate",     "Noise S&H Rate",  1.0f, 19 },
            { "ex_wave_noise",  "Wave/Noise Mix",  0.0f, 20 },
            { "ex_level",       "Exciter Level",   0.7f, 21 },

            { "env_onset",      "Onset Delay",     0.0f, 22 },
            { "env_attack",     "Attack",          0.02f,23 },
            { "env_decay",      "Decay",           0.3f, 24 },
            { "env_sustain",    "Sustain",         1.0f, 25 },
            { "env_release",    "Release",         0.15f,26 },

            { "res_in_filter",  "Input Filter",    1.0f, 31 },
            { "res_fb_filter",  "Feedback Filter", 0.7f, 40 },
            { "res_feedback",   "Feedback",        0.0f, 43 },
            { "res_fine_tune",  "Fine Tune",       0.5f, 46 },
            { "res_glide",      "Glide",           0.0f,  5 },

            { "out_drywet",     "Dry/Wet",         0.0f, 48 },
            { "out_pan",        "Panning",         0.5f, 10 },
            { "out_level",      "Level",           0.8f,  7 },
            { "wild_tame",      "Wild/Tame",       0.4f, -1 },
            { "master",         "Master",          0.8f, -1 },
        };
        return table[static_cast<int>(p)];
    }
}
